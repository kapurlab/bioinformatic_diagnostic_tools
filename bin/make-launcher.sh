#!/usr/bin/env bash
# make-launcher.sh — build a double-clickable desktop launcher for the dashboard.
#
#   bdtools make-launcher [--dest DIR] [--name NAME] [--port N] [--force]
#
# macOS   -> "<NAME>.app"        (a real bundle: icon, no Terminal window)
# Linux   -> "<NAME>.desktop"    (+ icons in the hicolor theme)
# WSL     -> the Linux launcher, and the .ico for a Windows shortcut
#
# Why a generated launcher and not a checked-in file:
#
#  * "Open Dashboard.command" is opened BY Terminal.app, which is the only reason
#    a terminal window appears. A .app whose executable is a shell script shows
#    none, and being generated locally it is not quarantined, so it opens on the
#    first double-click with no right-click -> Open dance.
#  * The install path is baked in at generation time. The old launcher used
#    `cd "$(dirname "$0")"`, which works only while the file sits inside the
#    checkout — copy it to the Desktop, the very thing you want to do, and it
#    breaks. Regenerate after moving the install.
#  * The dashboard is started DETACHED. It outlives the launcher, so quitting the
#    app (or Cmd-Q, or logging the launcher out of the Dock) cannot take a running
#    analysis with it. Stop it from the browser's Shut down button.
#
# Output goes to a log file, because there is no terminal to print to. If the
# dashboard does not come up, the launcher says so in a dialog and names the log.
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

NAME="Kapur Lab Dashboard"
DEST=""
PORT=""
FORCE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dest)   DEST="${2:?--dest needs a directory}"; shift 2;;
    --dest=*) DEST="${1#--dest=}"; shift;;
    --name)   NAME="${2:?--name needs a name}"; shift 2;;
    --name=*) NAME="${1#--name=}"; shift;;
    --port)   PORT="${2:?--port needs a number}"; shift 2;;
    --port=*) PORT="${1#--port=}"; shift;;
    --force)  FORCE=1; shift;;
    -h|--help) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
    *) die "unknown option: $1 (see: bdtools make-launcher --help)";;
  esac
done
[[ -z "${PORT}" || "${PORT}" =~ ^[0-9]+$ ]] || die "--port must be a number, got '${PORT}'"

# Write stdin to a file, honouring --dry-run like run() does.
write_out() {
  if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "  [dry-run] write $1"; cat >/dev/null
  else
    cat > "$1"
  fi
}

REPO="${REPO_DIR}"
[[ -x "${REPO}/bin/bdtools" ]] || die "cannot find bin/bdtools under ${REPO}"
ICONS="${REPO}/templates/launcher/icons"
[[ -f "${ICONS}/bdtools-dashboard.icns" ]] || die "icons are missing from ${ICONS}
       Regenerate them with:  <tool>/env/bin/python bin/make-icons.py"

# BDTOOLS_LAUNCHER_PLATFORM forces the target. It exists so the macOS bundle can be
# built and checked on a Linux box (a .app is a directory, not a compiled binary) —
# otherwise that path could only ever be tested by hand on someone's laptop.
case "${BDTOOLS_LAUNCHER_PLATFORM:-$(uname -s)}" in
  macos|Darwin) PLATFORM=macos;;
  wsl)          PLATFORM=wsl;;
  linux)        PLATFORM=linux;;
  Linux)  if grep -qi microsoft /proc/version 2>/dev/null; then PLATFORM=wsl; else PLATFORM=linux; fi;;
  *)      die "no launcher template for $(uname -s) — start the dashboard with: bin/bdtools dashboard";;
esac

# ---------------------------------------------------------------------------
# The launcher body, shared by every platform. $1 is where the dialog helper
# lives, so the same logic can raise an alert with osascript or zenity.
# ---------------------------------------------------------------------------
emit_launcher() {  # emit_launcher <logdir> <alert-fn-body>
  local logdir="$1" alert_body="$2"
  cat <<EOF
#!/bin/bash
# Generated by \`bdtools make-launcher\` — do not edit by hand.
# Regenerate it (after moving or reinstalling the suite) with:
#     "${REPO}/bin/bdtools" make-launcher
REPO="${REPO}"
PORT="${PORT:-8080}"
LOGDIR="${logdir}"
LOG="\${LOGDIR}/dashboard.log"

alert() {  # alert <title> <message>
${alert_body}
}

if [[ ! -x "\${REPO}/bin/bdtools" ]]; then
  alert "Dashboard not found" \\
    "The tools are no longer at:

\${REPO}

If you moved or reinstalled them, open a terminal in the new location and run:

    bin/bdtools make-launcher"
  exit 1
fi

mkdir -p "\${LOGDIR}"
# Keep the log from growing without bound, but keep one generation: the reason a
# launch failed is usually in the run before the one you are looking at.
if [[ -f "\${LOG}" ]]; then
  size=\$(wc -c <"\${LOG}" 2>/dev/null || echo 0)
  [[ "\${size}" -gt 2000000 ]] && mv -f "\${LOG}" "\${LOG}.1"
fi
{
  echo
  echo "=============================================================="
  echo "\$(date '+%Y-%m-%d %H:%M:%S')  launching dashboard from \${REPO}"
} >>"\${LOG}" 2>&1

# Detached, in its own session where possible, so it survives this launcher
# exiting AND the app being quit. A dashboard whose lifetime is tied to a Dock
# icon would let Cmd-Q kill a running analysis.
if command -v setsid >/dev/null 2>&1; then
  setsid nohup "\${REPO}/bin/bdtools" dashboard --port "\${PORT}" >>"\${LOG}" 2>&1 &
else
  ( trap '' HUP; nohup "\${REPO}/bin/bdtools" dashboard --port "\${PORT}" >>"\${LOG}" 2>&1 & )
fi

# Wait for it to actually answer before declaring success. bdtools opens the
# browser itself; all we add is the failure path, which without a terminal would
# otherwise be complete silence.
#
# Any HTTP status means a live server, including 403 — that is the session-key
# challenge, not a failure. Only "no answer at all" counts as not started.
if ! command -v curl >/dev/null 2>&1; then
  exit 0        # nothing to probe with; the log is the only record either way
fi
for _ in \$(seq 1 60); do
  sleep 1
  code="\$(curl -s -o /dev/null -m 2 -w '%{http_code}' "http://127.0.0.1:\${PORT}/" 2>/dev/null || true)"
  [[ -n "\${code}" && "\${code}" != "000" ]] && exit 0
done

alert "The dashboard did not start" \\
  "It was launched but nothing is answering on port \${PORT}.

The reason is at the end of this log file:

\${LOG}

Last lines:

\$(tail -n 12 "\${LOG}" 2>/dev/null | sed 's/"/\\\\"/g')"
exit 1
EOF
}

MAC_ALERT='  /usr/bin/osascript -e "display alert \"$1\" message \"$2\" as critical" >/dev/null 2>&1 || true'
LINUX_ALERT='  if command -v zenity >/dev/null 2>&1; then
    zenity --error --no-wrap --title="$1" --text="$2" >/dev/null 2>&1 || true
  elif command -v kdialog >/dev/null 2>&1; then
    kdialog --error "$1

$2" >/dev/null 2>&1 || true
  elif command -v notify-send >/dev/null 2>&1; then
    notify-send -u critical "$1" "$2" >/dev/null 2>&1 || true
  else
    printf "%s\n\n%s\n" "$1" "$2" >&2
  fi'

make_macos_app() {
  local dest="${DEST:-${HOME}/Desktop}"
  [[ -d "${dest}" ]] || dest="${HOME}/Applications"
  mkdir -p "${dest}"
  local app="${dest}/${NAME}.app"
  if [[ -e "${app}" && ${FORCE} -eq 0 ]]; then
    # Replacing is the normal case (regenerating after a move), so do it — but
    # only for something that is actually one of ours.
    [[ -f "${app}/Contents/MacOS/launch" ]] \
      || die "${app} exists and was not made by bdtools — pass --force to replace it"
  fi
  run rm -rf "${app}"
  run mkdir -p "${app}/Contents/MacOS" "${app}/Contents/Resources"

  local ver; ver="$(manifest_suite_version 2>/dev/null || echo 1.0)"
  write_out "${app}/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${NAME}</string>
  <key>CFBundleDisplayName</key><string>${NAME}</string>
  <key>CFBundleIdentifier</key><string>org.kapurlab.bdtools.dashboard</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>bdtools-dashboard</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleSignature</key><string>????</string>
  <key>CFBundleShortVersionString</key><string>${ver}</string>
  <key>CFBundleVersion</key><string>${ver}</string>
  <key>LSMinimumSystemVersion</key><string>10.13</string>
  <key>NSHighResolutionCapable</key><true/>
  <!-- No Dock menu of its own: the launcher hands off to a detached dashboard
       and exits, so there is nothing for a Quit command to act on. -->
  <key>LSBackgroundOnly</key><false/>
</dict>
</plist>
EOF
  printf 'APPL????' > "${app}/Contents/PkgInfo"
  emit_launcher "\${HOME}/Library/Logs/bdtools" "${MAC_ALERT}" \
    > "${app}/Contents/MacOS/launch"
  chmod +x "${app}/Contents/MacOS/launch"
  run cp "${ICONS}/bdtools-dashboard.icns" "${app}/Contents/Resources/"
  # Bump the bundle's mtime so Finder re-reads Info.plist instead of showing a
  # cached generic icon for a path it has seen before.
  touch "${app}"

  ok "created ${app}"
  info "  Double-click it. No terminal window appears; your browser opens instead."
  info "  Drag it to the Desktop, the Dock, or /Applications — the install path is"
  info "  baked in, so it keeps working. Re-run this after moving the tools."
  info "  Log: ~/Library/Logs/bdtools/dashboard.log"
}

make_linux_desktop() {
  local apps="${HOME}/.local/share/applications"
  local bindir="${BDTOOLS_HOME}/bin"
  local icondir="${HOME}/.local/share/icons/hicolor"
  run mkdir -p "${apps}" "${bindir}"
  emit_launcher "\${XDG_STATE_HOME:-\${HOME}/.local/state}/bdtools" "${LINUX_ALERT}" \
    > "${bindir}/bdtools-dashboard-launch"
  chmod +x "${bindir}/bdtools-dashboard-launch"

  local size
  for size in 16 24 32 48 64 128 256 512; do
    run mkdir -p "${icondir}/${size}x${size}/apps"
    run cp "${ICONS}/bdtools-dashboard-${size}.png" \
           "${icondir}/${size}x${size}/apps/bdtools-dashboard.png"
  done
  command -v gtk-update-icon-cache >/dev/null 2>&1 \
    && gtk-update-icon-cache -q -t -f "${icondir}" >/dev/null 2>&1 || true

  local entry="${apps}/bdtools-dashboard.desktop"
  write_out "${entry}" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=${NAME}
GenericName=Bioinformatic diagnostic tools
Comment=Open the Kapur Lab diagnostic tools dashboard in your browser
Exec=${bindir}/bdtools-dashboard-launch
Icon=bdtools-dashboard
Terminal=false
StartupNotify=true
Categories=Science;Biology;Education;
Keywords=bioinformatics;vSNP;AMR;kraken;MLST;sequencing;
EOF
  chmod +x "${entry}"
  command -v update-desktop-database >/dev/null 2>&1 \
    && update-desktop-database -q "${apps}" >/dev/null 2>&1 || true

  ok "created ${entry}"
  info "  It is now in your applications menu as “${NAME}”."
  if [[ -n "${DEST}" ]]; then
    run cp "${entry}" "${DEST}/${NAME}.desktop"
    chmod +x "${DEST}/${NAME}.desktop"
    # GNOME/Nautilus refuses to launch an untrusted .desktop file dropped on the
    # Desktop; without this it shows as a text file and does nothing when opened.
    command -v gio >/dev/null 2>&1 \
      && gio set "${DEST}/${NAME}.desktop" metadata::trusted true >/dev/null 2>&1 || true
    ok "copied it to ${DEST}/${NAME}.desktop"
    info "  If your desktop shows it as a text file, right-click → Allow Launching."
  else
    info "  For a copy on the Desktop too:  bdtools make-launcher --dest ~/Desktop"
  fi
  info "  Log: \${XDG_STATE_HOME:-~/.local/state}/bdtools/dashboard.log"
}

case "${PLATFORM}" in
  macos) make_macos_app;;
  linux) make_linux_desktop;;
  wsl)
    make_linux_desktop
    info ""
    info "WSL: WSLg already surfaces the entry above in the Windows Start Menu."
    info "  For a Windows shortcut of your own, point it at:"
    info "     wsl.exe -e ${BDTOOLS_HOME}/bin/bdtools-dashboard-launch"
    info "  and use this icon:"
    info "     ${ICONS}/bdtools-dashboard.ico"
    ;;
esac
